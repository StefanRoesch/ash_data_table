defmodule DemoWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :demo

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_demo_key",
    signing_salt: "iNGQijPg",
    same_site: "Lax"
  ]

  # The browser tests (config/e2e.exs): each test runs in a database
  # transaction of its own, which it starts with `POST /sandbox` and ends
  # with `DELETE /sandbox`. Its browser sends what the `POST` answered as its
  # user agent; the plug allows every request with it into that transaction,
  # and `DemoWeb.E2E.Sandbox` every LiveView, which reads it from the
  # socket's `connect_info`. As `Phoenix.Ecto.SQL.Sandbox` describes it.
  @sql_sandbox Application.compile_env(:demo, :sql_sandbox, false)

  if @sql_sandbox do
    plug Phoenix.Ecto.SQL.Sandbox, at: "/sandbox", repo: Demo.Repo, timeout: 300_000
  end

  @connect_info if @sql_sandbox,
                  do: [:user_agent, session: @session_options],
                  else: [session: @session_options]

  # `compress: true`: permessage-deflate on the LiveView socket. A table's
  # patches repeat their markup, and deflate takes a page change to a fraction
  # of its bytes (demo/perf, PERF_WIRE=1).
  socket "/live", Phoenix.LiveView.Socket,
    websocket: [compress: true, connect_info: @connect_info],
    longpoll: [connect_info: @connect_info]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :demo,
    gzip: not code_reloading?,
    only: DemoWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Tidewave: an MCP endpoint into the running demo for coding agents, at
  # /tidewave/mcp. The dependency is `only: :dev`, so no other environment
  # has the plug. It answers requests from this machine only
  # (`allow_remote_access` is false by default). Without the toolbar: with it,
  # every page would load a script from tidewave.ai.
  if Code.ensure_loaded?(Tidewave) do
    plug Tidewave, toolbar: false
  end

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug AshPhoenix.Plug.CheckCodegenStatus
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :demo
  end

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug DemoWeb.Router
end
