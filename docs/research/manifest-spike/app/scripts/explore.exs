alias Ash.Info.Manifest
{:ok, m} = Manifest.generate(otp_app: :spike)
IO.inspect(Map.keys(m), label: "manifest keys")
IO.inspect(Enum.map(m.resources, & &1.module), label: "resources")
IO.inspect(Enum.map(m.types, &{&1.kind, &1.module}), label: "types")
IO.inspect(length(m.entrypoints), label: "entrypoints")
p = Manifest.get_resource(Manifest.resource_lookup(m), Spike.Shop.Product)
IO.inspect(p |> Map.from_struct() |> Map.drop([:fields, :relationships]), label: "product")
IO.inspect(Map.keys(p.fields), label: "field keys (map order)")
IO.inspect(p.fields[:name], label: "name field", limit: :infinity)
IO.inspect(p.fields[:status] |> Map.take([:type, :has_default?]), label: "status")
IO.inspect(p.fields[:sku].type, label: "sku type")
IO.inspect(p.fields[:size].type, label: "size type")
IO.inspect(p.fields[:keywords].type, label: "keywords type")
IO.inspect(p.fields[:dimensions].type, label: "dimensions type")
IO.inspect(p.fields[:big_blob] |> Map.take([:filterable?, :sortable?, :filter_operators, :filter_functions]), label: "big_blob")
IO.inspect(p.fields[:stock_value] |> Map.drop([:filter_operators, :filter_functions]), label: "calc expr")
IO.inspect(p.fields[:margin] |> Map.take([:kind, :filterable?, :sortable?, :type]), label: "calc module")
IO.inspect(p.fields[:review_count] |> Map.drop([:filter_operators, :filter_functions]), label: "agg")
IO.inspect(p.relationships, label: "rels")
IO.inspect(Map.has_key?(p.fields, :internal_note), label: "internal_note in fields?")
IO.inspect(Map.has_key?(p.fields, :category_id), label: "category_id in fields?")
IO.inspect(Map.has_key?(p.fields, :owned_by_id), label: "owned_by_id in fields?")

for a <- [:read, :search, :unpaginated, :update, :set_price, :set_internal_note, :restock, :set_tags, :publish, :rename] do
  act = Manifest.get_action(Manifest.action_lookup(m), Spike.Shop.Product, a)
  IO.inspect(act && Map.drop(Map.from_struct(act), [:custom, :metadata]), label: "action #{a}", limit: :infinity)
end

IO.inspect(Manifest.get_type(Manifest.type_lookup(m), Spike.Types.Status), label: "Status type")
IO.inspect(Manifest.get_type(Manifest.type_lookup(m), Spike.Types.Sku), label: "Sku type")
IO.inspect(m.sort_capabilities, label: "sort caps")
IO.inspect(Enum.map(m.filter_capabilities.operators, & &1.name), label: "ops")
IO.inspect(Enum.map(m.filter_capabilities.functions, & &1.name), label: "fns")
